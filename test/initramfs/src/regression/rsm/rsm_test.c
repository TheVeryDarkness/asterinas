static const unsigned long artifact_len = sizeof(artifact);

// Matches `RsmStats` in kernel/core/src/syscall/rsm.rs.
struct rsm_stats {
    uint64_t counter;
    uint64_t invocations;
};

#define SYS_RSM_LOAD 500
#define SYS_RSM_ATTACH 501
#define SYS_RSM_DETACH 502
#define SYS_RSM_READ_STATS 503

int main(void)
{
    if (syscall(SYS_RSM_LOAD, artifact, artifact_len) < 0) {
        perror("RSM_LOAD");
        return 1;
    }
    if (syscall(SYS_RSM_ATTACH) < 0) {
        perror("RSM_ATTACH");
        return 1;
    }

    for (int i = 0; i < 5; i++) {
        if (syscall(SYS_getpid) < 0) {
            perror("getpid");
            return 1;
        }
    }

    struct rsm_stats stats = { 0, 0 };
    if (syscall(SYS_RSM_READ_STATS, &stats) < 0) {
        perror("RSM_READ_STATS");
        return 1;
    }
    syscall(SYS_RSM_DETACH);

    printf("counter=%llu invocations=%llu\n",
           (unsigned long long)stats.counter,
           (unsigned long long)stats.invocations);

    if (stats.counter != 5 || stats.invocations != 5) {
        fprintf(stderr, "expected counter=5 invocations=5\n");
        return 1;
    }
    return 0;
}
