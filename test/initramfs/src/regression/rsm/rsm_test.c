static const unsigned long artifact_len = sizeof(artifact);

// RSM commands multiplexed through SYS_RSM (matches RsmCmd in rsm.rs).
#define SYS_RSM 500
#define RSM_CMD_LOAD 0
#define RSM_CMD_ATTACH 1
#define RSM_CMD_DETACH 2

int main(void)
{
    if (syscall(SYS_RSM, RSM_CMD_LOAD, artifact, artifact_len) < 0) {
        perror("RSM_LOAD");
        return 1;
    }
    if (syscall(SYS_RSM, RSM_CMD_ATTACH) < 0) {
        perror("RSM_ATTACH");
        return 1;
    }

    // Each observed system call makes the observer print its number (decimal
    // digits) through rsm_printk. getpid is 39 on x86-64.
    for (int i = 0; i < 10; i++) {
        if (syscall(SYS_getpid) < 0) {
            perror("getpid");
            return 1;
        }
    }

    syscall(SYS_RSM, RSM_CMD_DETACH);

    int fd = open("/proc/rsm_log", O_RDONLY);
    if (fd < 0) {
        perror("open /proc/rsm_log");
        return 1;
    }
    char log[2048];
    ssize_t n = read(fd, log, sizeof(log) - 1);
    close(fd);
    if (n < 0) {
        perror("read /proc/rsm_log");
        return 1;
    }
    log[n] = '\0';

    printf("rsm_log (%zd bytes): %s\n", n, log);

    if (n == 0) {
        fprintf(stderr, "rsm_log is empty\n");
        return 1;
    }
    if (strstr(log, "39") == NULL) {
        fprintf(stderr, "rsm_log does not record getpid (39)\n");
        return 1;
    }
    return 0;
}
